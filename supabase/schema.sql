-- ---------- Tablas ----------
create table if not exists public.profiles (
  id              uuid primary key references auth.users(id) on delete cascade,
  nombre          text not null default '',
  restricciones   text[] not null default '{}',   -- Nodo 3: lactosa, gluten, frutos_secos, huevo, azucar, cafeina
  preferencias    text[] not null default '{}',   -- Nodo 2: cafe, dulce, salado, saludable, frio, caliente
  perfil_completo boolean not null default false, -- Hito 1 completado
  rol             text not null default 'cliente' check (rol in ('cliente','admin')),
  created_at      timestamptz not null default now()
);

create table if not exists public.productos (
  id             bigint generated by default as identity primary key,
  nombre         text not null,
  descripcion    text,
  precio         integer not null check (precio >= 0),
  categoria      text not null,
  emoji          text,
  alergenos      text[] not null default '{}',
  gustos         text[] not null default '{}',
  momento        text[] not null default '{}',
  personalizable boolean not null default false,
  stock          integer not null default 0 check (stock >= 0),
  disponible     boolean not null default true
);

create table if not exists public.pedidos (
  id          bigint generated by default as identity primary key,
  usuario_id  uuid not null references public.profiles(id) on delete cascade,
  canal       text not null default 'movil' check (canal in ('movil','kiosco')),
  estado      text not null default 'pendiente' check (estado in ('pendiente','preparando','listo','entregado')),
  mood        text check (mood in ('feliz','cansado','estresado','hambre')),  -- Nodo 4 (voluntario)
  total       integer not null default 0,
  created_at  timestamptz not null default now()
);

create table if not exists public.pedido_items (
  id              bigint generated by default as identity primary key,
  pedido_id       bigint not null references public.pedidos(id) on delete cascade,
  producto_id     bigint not null references public.productos(id),
  cantidad        integer not null check (cantidad > 0),
  opciones        jsonb,                          -- {tamano, leche, extra}
  precio_unitario integer not null,
  recomendado     boolean not null default false  -- para medir la aceptación de recomendaciones
);

create index if not exists pedidos_usuario_idx on public.pedidos(usuario_id);
create index if not exists pedido_items_pedido_idx on public.pedido_items(pedido_id);

-- ---------- Funciones auxiliares ----------
create or replace function public.es_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and rol = 'admin');
$$;

-- Crea el perfil automáticamente cuando alguien se registra
create or replace function public.crear_perfil()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, nombre)
  values (new.id, coalesce(new.raw_user_meta_data->>'nombre', split_part(new.email, '@', 1)));
  return new;
end;
$$;
drop trigger if exists al_crear_usuario on auth.users;
create trigger al_crear_usuario after insert on auth.users
  for each row execute function public.crear_perfil();

-- Impide que un cliente se autoasigne el rol de administrador
create or replace function public.proteger_rol()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  -- auth.uid() es nulo cuando se ejecuta desde el SQL Editor (permitido)
  if new.rol is distinct from old.rol and auth.uid() is not null and not public.es_admin() then
    new.rol := old.rol;
  end if;
  return new;
end;
$$;
drop trigger if exists proteger_rol on public.profiles;
create trigger proteger_rol before update on public.profiles
  for each row execute function public.proteger_rol();

-- ¿Es apto el producto para estas restricciones? (la lactosa no excluye bebidas personalizables)
create or replace function public.es_compatible(p public.productos, restricciones text[])
returns boolean language sql immutable as $$
  select not exists (
    select 1 from unnest(coalesce(restricciones, '{}')) r
    where r = any(p.alergenos) and not (r = 'lactosa' and p.personalizable)
  );
$$;

-- Nodo 3: menú filtrado A NIVEL DE BASE DE DATOS según las intolerancias del cliente
create or replace function public.menu_para_mi()
returns setof public.productos
language sql stable security definer set search_path = public as $$
  select p.* from productos p
  where p.disponible
    and public.es_compatible(p, (select restricciones from profiles where id = auth.uid()))
  order by p.id;
$$;

-- Precio de una línea con sus opciones (tamaño, leche, extra shot)
create or replace function public.precio_linea(p public.productos, op jsonb)
returns integer language sql immutable as $$
  select p.precio + case when p.personalizable and op is not null then
      (case op->>'tamano' when 'mediano' then 1500 when 'grande' then 3000 else 0 end)
    + (case op->>'leche'  when 'almendras' then 1500 when 'avena' then 1000 else 0 end)
    + (case when coalesce((op->>'extra')::boolean, false) then 2000 else 0 end)
  else 0 end;
$$;

-- Gestor de pedidos: valida restricciones y stock, calcula precios EN EL SERVIDOR y descuenta inventario
create or replace function public.crear_pedido(p_items jsonb, p_canal text default 'movil', p_mood text default null)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_pedido bigint;
  v_total  integer := 0;
  v_restr  text[];
  it       jsonb;
  prod     productos;
  v_cant   integer;
  v_op     jsonb;
  v_precio integer;
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión'; end if;
  if jsonb_array_length(p_items) = 0 then raise exception 'El pedido está vacío'; end if;
  select restricciones into v_restr from profiles where id = auth.uid();

  insert into pedidos (usuario_id, canal, mood) values (auth.uid(), coalesce(p_canal, 'movil'), p_mood)
  returning id into v_pedido;

  for it in select * from jsonb_array_elements(p_items) loop
    select * into prod from productos where id = (it->>'producto_id')::bigint and disponible for update;
    if not found then raise exception 'Producto no disponible: %', it->>'producto_id'; end if;
    if not public.es_compatible(prod, v_restr) then raise exception '% no es compatible con tus restricciones', prod.nombre; end if;
    v_cant := greatest(1, (it->>'cantidad')::int);
    if prod.stock < v_cant then raise exception 'No hay suficiente stock de %', prod.nombre; end if;
    v_op := case when prod.personalizable then it->'opciones' else null end;
    if v_op is not null and (
         ('lactosa' = any(v_restr) and v_op->>'leche' = 'entera') or
         ('frutos_secos' = any(v_restr) and v_op->>'leche' = 'almendras') or
         ('cafeina' = any(v_restr) and coalesce((v_op->>'extra')::boolean, false))) then
      raise exception 'Las opciones elegidas para % no son compatibles con tus restricciones', prod.nombre;
    end if;
    v_precio := public.precio_linea(prod, v_op);
    insert into pedido_items (pedido_id, producto_id, cantidad, opciones, precio_unitario, recomendado)
      values (v_pedido, prod.id, v_cant, v_op, v_precio, coalesce((it->>'recomendado')::boolean, false));
    update productos set stock = stock - v_cant where id = prod.id;
    v_total := v_total + v_precio * v_cant;
  end loop;

  update pedidos set total = v_total where id = v_pedido;
  return v_pedido;
end;
$$;

-- Estadísticas agregadas y anónimas para el motor de recomendación
create or replace function public.productos_populares()
returns table (producto_id bigint, veces bigint)
language sql stable security definer set search_path = public as $$
  select producto_id, count(distinct pedido_id) from pedido_items group by producto_id;
$$;

create or replace function public.coocurrencias()
returns table (a bigint, b bigint, veces bigint)
language sql stable security definer set search_path = public as $$
  select x.producto_id, y.producto_id, count(distinct x.pedido_id)
  from pedido_items x
  join pedido_items y on x.pedido_id = y.pedido_id and x.producto_id <> y.producto_id
  group by x.producto_id, y.producto_id;
$$;

