-- ---------- Tablas ----------
create table if not exists public.profiles (
  id            uuid primary key references auth.users(id) on delete cascade,
  nombre        text not null default '',
  restricciones text[] not null default '{}',
  rol           text not null default 'cliente' check (rol in ('cliente','admin')),
  created_at    timestamptz not null default now()
);

create table if not exists public.productos (
  id          bigint generated by default as identity primary key,
  nombre      text not null,
  descripcion text,
  precio      integer not null check (precio >= 0),
  categoria   text not null,
  emoji       text,
  etiquetas   text[] not null default '{}',
  momento     text[] not null default '{}',
  disponible  boolean not null default true
);

create table if not exists public.pedidos (
  id          bigint generated by default as identity primary key,
  usuario_id  uuid not null references public.profiles(id) on delete cascade,
  canal       text not null default 'movil' check (canal in ('movil','kiosco')),
  estado      text not null default 'pendiente' check (estado in ('pendiente','preparando','listo','entregado')),
  total       integer not null default 0,
  created_at  timestamptz not null default now()
);

create table if not exists public.pedido_items (
  id              bigint generated by default as identity primary key,
  pedido_id       bigint not null references public.pedidos(id) on delete cascade,
  producto_id     bigint not null references public.productos(id),
  cantidad        integer not null check (cantidad > 0),
  precio_unitario integer not null
);

create index if not exists pedidos_usuario_idx on public.pedidos(usuario_id);
create index if not exists pedido_items_pedido_idx on public.pedido_items(pedido_id);

-- ---------- Funciones auxiliares ----------
create or replace function public.es_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and rol = 'admin');
$$;

-- Crea el perfil automáticamente cuando alguien se registra
create or replace function public.crear_perfil()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, nombre)
  values (new.id, coalesce(new.raw_user_meta_data->>'nombre', split_part(new.email, '@', 1)));
  return new;
end;
$$;
drop trigger if exists al_crear_usuario on auth.users;
create trigger al_crear_usuario after insert on auth.users
  for each row execute function public.crear_perfil();

-- Impide que un cliente se autoasigne el rol de administrador
create or replace function public.proteger_rol()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  -- auth.uid() es nulo cuando se ejecuta desde el SQL Editor (permitido)
  if new.rol is distinct from old.rol and auth.uid() is not null and not public.es_admin() then
    new.rol := old.rol;
  end if;
  return new;
end;
$$;
drop trigger if exists proteger_rol on public.profiles;
create trigger proteger_rol before update on public.profiles
  for each row execute function public.proteger_rol();

-- Crea un pedido calculando los precios EN EL SERVIDOR (el cliente no puede alterar el total)
create or replace function public.crear_pedido(p_items jsonb, p_canal text default 'movil')
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_pedido bigint;
  v_total  integer := 0;
  it       jsonb;
  v_precio integer;
begin
  if auth.uid() is null then raise exception 'Debes iniciar sesión'; end if;
  if jsonb_array_length(p_items) = 0 then raise exception 'El pedido está vacío'; end if;

  insert into pedidos (usuario_id, canal) values (auth.uid(), coalesce(p_canal, 'movil'))
  returning id into v_pedido;

  for it in select * from jsonb_array_elements(p_items) loop
    select precio into v_precio from productos
      where id = (it->>'producto_id')::bigint and disponible;
    if v_precio is null then raise exception 'Producto no disponible: %', it->>'producto_id'; end if;
    insert into pedido_items (pedido_id, producto_id, cantidad, precio_unitario)
      values (v_pedido, (it->>'producto_id')::bigint, greatest(1, (it->>'cantidad')::int), v_precio);
    v_total := v_total + v_precio * greatest(1, (it->>'cantidad')::int);
  end loop;

  update pedidos set total = v_total where id = v_pedido;
  return v_pedido;
end;
$$;

-- Estadísticas agregadas y anónimas para el motor de recomendación
create or replace function public.productos_populares()
returns table (producto_id bigint, veces bigint)
language sql stable security definer set search_path = public as $$
  select producto_id, count(distinct pedido_id) from pedido_items group by producto_id;
$$;

create or replace function public.coocurrencias()
returns table (a bigint, b bigint, veces bigint)
language sql stable security definer set search_path = public as $$
  select x.producto_id, y.producto_id, count(distinct x.pedido_id)
  from pedido_items x
  join pedido_items y on x.pedido_id = y.pedido_id and x.producto_id <> y.producto_id
  group by x.producto_id, y.producto_id;
$$;

-- ---------- Seguridad a nivel de fila (RLS) ----------
alter table public.profiles     enable row level security;
alter table public.productos    enable row level security;
alter table public.pedidos      enable row level security;
alter table public.pedido_items enable row level security;

drop policy if exists "perfil propio o admin" on public.profiles;
create policy "perfil propio o admin" on public.profiles
  for select using (id = auth.uid() or public.es_admin());
drop policy if exists "editar perfil propio" on public.profiles;
create policy "editar perfil propio" on public.profiles
  for update using (id = auth.uid() or public.es_admin());

drop policy if exists "productos visibles" on public.productos;
create policy "productos visibles" on public.productos
  for select using (true);
drop policy if exists "admin gestiona productos" on public.productos;
create policy "admin gestiona productos" on public.productos
  for all using (public.es_admin()) with check (public.es_admin());

drop policy if exists "ver pedidos propios o admin" on public.pedidos;
create policy "ver pedidos propios o admin" on public.pedidos
  for select using (usuario_id = auth.uid() or public.es_admin());
drop policy if exists "admin actualiza pedidos" on public.pedidos;
create policy "admin actualiza pedidos" on public.pedidos
  for update using (public.es_admin());

drop policy if exists "ver items propios o admin" on public.pedido_items;
create policy "ver items propios o admin" on public.pedido_items
  for select using (exists (
    select 1 from public.pedidos p where p.id = pedido_id and (p.usuario_id = auth.uid() or public.es_admin())
  ));
-- (Los pedidos e ítems se insertan solo a través de crear_pedido)

grant execute on function public.crear_pedido(jsonb, text) to authenticated;
grant execute on function public.productos_populares() to authenticated;
grant execute on function public.coocurrencias() to authenticated;

